"""Thin ADB wrapper around ``adbutils`` (optional ``[device]`` extra).

The module itself imports cleanly without adbutils/Pillow installed --
the dependency is resolved lazily on :meth:`AdbDevice.connect`, so the rest
of the code base (sim lab, CI without a phone) never pays for it. Everything that talks
to a real phone obviously cannot run until one is plugged in; those methods
fail with :class:`DeviceError` when not connected.

SAFETY: swipes are only generated by :class:`bot2048.device.humanizer.
Humanizer`, which clamps every endpoint into the board's safe zone (never
near the status bar / notification shade). Taps are only issued at
calibrated button coordinates -- there is deliberately no "explore the
screen" API here.
"""

from __future__ import annotations

import importlib
import io
import time
from typing import Any, cast

import numpy as np
import numpy.typing as npt
import structlog

from bot2048.core.types import Direction
from bot2048.device.config import DeviceConfig
from bot2048.device.humanizer import BBox, Humanizer, SwipeParams
from bot2048.device.swipe_shell import PersistentSwipeShell, SwipeShellError

log = structlog.get_logger(__name__)

#: One-time debug note for :meth:`AdbDevice.screenshot` (screencap is primary).
_SCREENSHOT_PRIMARY_NOTED: bool = False

#: ``input keyevent`` code that wakes the screen without toggling it off.
KEYCODE_WAKEUP: int = 224


class DeviceError(RuntimeError):
    """ADB-level failure (no device, command failed, unexpected output)."""


class MissingDeviceDependencyError(DeviceError):
    """The optional ``[device]`` extra is not installed."""


class EmptyScreencapError(DeviceError):
    """``screencap -p`` returned 0 bytes on every retry.

    A single empty capture is a transient adb glitch, but a STABLY empty
    one (all retries) means a ``FLAG_SECURE`` window is on top -- on this
    device that is the monobank auth screen («Уведіть ПІН-код»). Callers
    should follow up with :meth:`AdbDevice.ui_dump` to distinguish
    AUTH_REQUIRED from a lost device (see bot2048.device.supervisor).
    """


def _import_adbutils() -> Any:
    try:
        return importlib.import_module("adbutils")
    except ImportError as exc:
        raise MissingDeviceDependencyError(
            "adbutils is not installed -- install the device extras on the host: "
            "pip install -e .[device]"
        ) from exc


def _import_pil_image() -> Any:
    try:
        return importlib.import_module("PIL.Image")
    except ImportError as exc:
        raise MissingDeviceDependencyError(
            "Pillow is not installed -- install the device extras on the host: "
            "pip install -e .[device]"
        ) from exc


def _adb_error_type() -> type[BaseException] | None:
    """The base adbutils error class (parent of ``AdbTimeout``), or ``None``.

    Resolved lazily -- callers reach it only after a real device call, so
    adbutils is installed; ``None`` is a defensive fallback that keeps a
    classification failure from masking the original exception.
    """
    try:
        return cast("type[BaseException]", importlib.import_module("adbutils.errors").AdbError)
    except Exception:  # pragma: no cover - adbutils always present past connect()
        return None


class AdbDevice:
    """One Android device reachable through the local adb server.

    Typical live-loop usage::

        device = AdbDevice(DeviceConfig(serial=None))
        device.connect()            # requires `adb devices` to show the phone
        device.wake()
        device.launch_app()
        image = device.screenshot() # RGB uint8 (H, W, 3)
        params = device.swipe_direction(Direction.LEFT, calibration.grid_bbox, humanizer)
    """

    def __init__(self, config: DeviceConfig | None = None) -> None:
        self.config = config or DeviceConfig()
        self._device: Any | None = None
        #: Lazily created on the first swipe; ``None`` = one-shot ``adb swipe``.
        self._swipe_shell: PersistentSwipeShell | None = None
        #: Set once persistent-shell setup has failed so we stop re-trying it
        #: and stay on the reliable one-shot path for the rest of the session.
        self._swipe_shell_disabled: bool = False

    # -- connection --------------------------------------------------------

    @property
    def is_connected(self) -> bool:
        return self._device is not None

    def connect(self) -> None:
        """Attach to the adb server and resolve the device.

        Raises:
            MissingDeviceDependencyError: ``[device]`` extra not installed.
            DeviceError: no (or ambiguous) device; run ``scripts/setup/setup_adb.sh``
                and check ``adb devices`` first (state must be ``device``).
        """
        adbutils = _import_adbutils()
        try:
            client = adbutils.AdbClient(host=self.config.adb_host, port=self.config.adb_port)
            self._device = (
                client.device(serial=self.config.serial)
                if self.config.serial is not None
                else client.device()
            )
        except Exception as exc:  # adbutils raises library-specific errors
            # The serial goes to the log, not into the exception text: an
            # unhandled DeviceError message is forwarded to Telegram.
            log.warning("adb.attach_failed", serial=self.config.serial)
            raise DeviceError(f"cannot attach to adb device: {type(exc).__name__}") from exc
        log.info("adb.connected", serial=self.config.serial, host=self.config.adb_host)

    def _dev(self) -> Any:
        if self._device is None:
            raise DeviceError("not connected -- call AdbDevice.connect() first")
        return self._device

    def _shell(self, cmdargs: Any, *, encoding: str | None = "utf-8") -> Any:
        """Run ONE blocking ``adb shell`` command under a real socket timeout.

        Every device I/O funnels through here so a half-open WiFi-ADB link can
        never make a call block FOREVER. adbutils arms the socket read with
        :attr:`DeviceConfig.adb_command_timeout_s` and raises ``AdbTimeout`` (an
        ``AdbError``) on expiry; we surface that -- and any other adb transport
        error -- as :class:`DeviceError`, the exact type the supervisor's
        EXISTING ``DEVICE_LOST`` -> reconnect ladder already recovers from (see
        ``runner/escalation.py`` and ``runner/session_recovery.py``). No new
        recovery path is invented.

        The bound sits far above every legitimate call (screencap ~0.65 s,
        swipe ~0.1 s, ui_dump << 1 s) AND above the runner's endgame search
        budget (<= 9 s, escalatable to ~15-20 s), so it can only trip a genuine
        stall, never a slow-but-honest operation -- config validation pins it
        at or above :data:`~bot2048.device.config.MIN_ADB_COMMAND_TIMEOUT_S`.
        """
        try:
            return self._dev().shell(
                cmdargs, timeout=self.config.adb_command_timeout_s, encoding=encoding
            )
        except DeviceError:
            raise  # not-connected / already-classified: keep the precise type
        except Exception as exc:
            adb_error = _adb_error_type()
            if adb_error is not None and isinstance(exc, adb_error):
                raise DeviceError(
                    f"adb shell command timed out or failed after "
                    f"{self.config.adb_command_timeout_s:g}s -- half-open link? "
                    f"({type(exc).__name__}: {exc})"
                ) from exc
            raise

    # -- observation ---------------------------------------------------------

    def _screencap_bytes(self) -> bytes:
        """One raw ``screencap -p`` capture. May legitimately be ``b""``."""
        out = self._shell("screencap -p", encoding=None)
        return bytes(out or b"")

    def _decode_png(self, raw: bytes) -> npt.NDArray[np.uint8]:
        pil_image = _import_pil_image()
        with pil_image.open(io.BytesIO(raw)) as img:
            arr = cast(
                npt.NDArray[np.uint8],
                np.asarray(img.convert("RGB"), dtype=np.uint8),
            )
        h, w = arr.shape[0], arr.shape[1]
        ew, eh = self.config.screen_size
        if (w, h) != (ew, eh):
            raise DeviceError(f"screenshot is {w}x{h}, expected {ew}x{eh} -- wrong device/DPI?")
        return arr

    def screenshot(self) -> npt.NDArray[np.uint8]:
        """Full-screen screenshot as RGB uint8 ``(H, W, 3)``.

        Runs raw ``screencap -p`` up to :attr:`DeviceConfig.screencap_retries`
        times (adb over USB occasionally drops a frame):

        * decodable PNG -> validated against ``screen_size`` and returned;
        * 0 bytes on EVERY attempt -> :class:`EmptyScreencapError` -- a
          ``FLAG_SECURE`` window is on top (the auth screen); the supervisor
          must confirm via :meth:`ui_dump`, NOT keep hammering screencap;
        * anything else exhausting the retries -> :class:`DeviceError`.

        .. note::
            Per-call ``screencap`` is the SUPPORTED PRIMARY capture path on
            this device (minicap ships no compatible ``.so`` for Android 13 /
            SDK 33) and the canonical AUTH_REQUIRED (0-byte) sensor -- see
            :meth:`bot2048.device.capture.ScreencapSource.is_auth_blocked`.
            :class:`bot2048.device.capture.FrameSource` and
            :mod:`bot2048.device.minicap` remain a seam for a future
            scrcpy-based swap.
        """
        global _SCREENSHOT_PRIMARY_NOTED
        if not _SCREENSHOT_PRIMARY_NOTED:
            _SCREENSHOT_PRIMARY_NOTED = True
            log.debug(
                "adb.screenshot_primary",
                hint="screencap is the primary capture path and the canonical "
                "AUTH_REQUIRED (0-byte) sensor",
            )
        attempts = self.config.screencap_retries
        empty_count = 0
        last_error: Exception | None = None
        for attempt in range(1, attempts + 1):
            raw: bytes | None
            try:
                raw = self._screencap_bytes()
            except Exception as exc:  # adb transport hiccup -- retryable
                raw = None
                last_error = exc
                log.warning("adb.screencap_failed", attempt=attempt, error=str(exc))
            if raw is not None:
                if len(raw) == 0:
                    empty_count += 1
                    log.warning("adb.screencap_empty", attempt=attempt)
                else:
                    try:
                        return self._decode_png(raw)
                    except (DeviceError, MissingDeviceDependencyError):
                        raise  # wrong size / missing extra: retrying cannot help
                    except Exception as exc:  # truncated PNG -- retryable
                        last_error = exc
                        log.warning(
                            "adb.screencap_undecodable",
                            attempt=attempt,
                            size=len(raw),
                            error=str(exc),
                        )
            if attempt < attempts:
                time.sleep(self.config.screencap_retry_delay_s)
        if empty_count == attempts:
            raise EmptyScreencapError(
                f"screencap returned 0 bytes on all {attempts} attempts -- "
                "FLAG_SECURE window on top (auth screen?); confirm via ui_dump()"
            )
        raise DeviceError(
            f"screenshot failed after {attempts} attempts "
            f"({empty_count} empty): {last_error}"
        )

    def ui_dump(self) -> str:
        """UI hierarchy XML via ``uiautomator dump`` (works under FLAG_SECURE).

        This is the ONLY observation channel on the auth screen, where
        screencap yields 0 bytes. The dump goes to a fixed file on the
        device, is catted back and removed.
        """
        remote = "/sdcard/bot2048_ui_dump.xml"
        self._shell(f"uiautomator dump {remote}")
        xml = cast(str, self._shell(f"cat {remote}"))
        self._shell(f"rm -f {remote}")
        if "<hierarchy" not in xml:
            raise DeviceError(
                f"uiautomator dump produced no hierarchy (got {len(xml)} chars)"
            )
        return xml

    # -- input ---------------------------------------------------------------

    def _ensure_swipe_shell(self) -> PersistentSwipeShell | None:
        """Return the persistent swipe shell, creating it on first use.

        Returns ``None`` (one-shot ``adb swipe`` path) when the feature is
        disabled by config or when setup fails once -- resolving the concrete
        serial and adb binary path can only fail when there is no real device
        behind :attr:`_device` (e.g. a test fake), and in that case we must not
        keep retrying every swipe.
        """
        if not self.config.persistent_swipe_shell or self._swipe_shell_disabled:
            return None
        if self._swipe_shell is None:
            try:
                serial = self.config.serial or self._dev().serial
                adb_path = cast(str, _import_adbutils().adb_path())
                self._swipe_shell = PersistentSwipeShell(
                    serial=serial,
                    adb_path=adb_path,
                    read_timeout_s=self.config.swipe_shell_timeout_s,
                )
            except Exception as exc:  # no real device / adb -- stay one-shot
                self._swipe_shell_disabled = True
                log.warning("adb.swipe_shell_unavailable", error=str(exc))
                return None
        return self._swipe_shell

    def _swipe_oneshot(self, params: SwipeParams) -> None:
        """Legacy per-call ``adb shell input swipe`` (spawns a fresh process).

        Issued directly as a timed ``shell`` (identical wire command to
        ``adbutils.swipe``) so the FALLBACK swipe carries the same
        :attr:`DeviceConfig.adb_command_timeout_s` socket bound as every other
        call -- otherwise fix #3's persistent-shell watchdog would merely move
        a half-open-link hang from the persistent shell onto this fallback.
        """
        self._shell(
            [
                "input",
                "swipe",
                str(params.x1),
                str(params.y1),
                str(params.x2),
                str(params.y2),
                str(params.duration_ms),
            ]
        )

    def swipe(self, params: SwipeParams) -> None:
        """Execute a pre-computed (already humanized + safe-zone clamped) swipe.

        Uses the persistent ``adb shell`` (no per-swipe process spawn, ~83 ms
        cheaper) when available, transparently falling back to a one-shot
        ``adb swipe`` if the shell is disabled or has died -- the move is never
        dropped on a shell failure.
        """
        shell = self._ensure_swipe_shell()
        transport = "oneshot"
        if shell is not None:
            try:
                shell.swipe(params.x1, params.y1, params.x2, params.y2, params.duration_ms)
                transport = "persistent"
            except SwipeShellError as exc:
                log.warning("adb.swipe_persistent_failed", error=str(exc))
                self._swipe_oneshot(params)
        else:
            self._swipe_oneshot(params)
        log.debug(
            "adb.swipe",
            x1=params.x1,
            y1=params.y1,
            x2=params.x2,
            y2=params.y2,
            duration_ms=params.duration_ms,
            transport=transport,
        )

    def swipe_direction(
        self,
        direction: Direction,
        grid_bbox: BBox,
        humanizer: Humanizer,
    ) -> SwipeParams:
        """Generate a humanized swipe for ``direction`` inside ``grid_bbox`` and run it.

        Returns the executed :class:`SwipeParams` so the runner can record them.
        """
        params = humanizer.swipe_params(direction, grid_bbox)
        self.swipe(params)
        return params

    def tap(self, x: int, y: int, *, sensitive: bool = False) -> None:
        """Tap at CALIBRATED coordinates only (e.g. the "New game" button).

        Never call this with guessed/exploratory coordinates -- a stray tap
        near the screen top can open the notification shade.

        ``sensitive=True`` suppresses the coordinates from the debug log. PIN
        entry uses it: the keypad layout is public (``ui_map.PIN_KEYS``), so a
        DEBUG-level log of tap coordinates during PIN entry is a cleartext
        transcript of the PIN, which would defeat the no-digits guarantee that
        :func:`bot2048.device.auth.enter_pin` makes one layer above.
        """
        self._shell(["input", "tap", str(x), str(y)])
        if sensitive:
            log.debug("adb.tap", sensitive=True)
        else:
            log.debug("adb.tap", x=x, y=y)

    def key_event(self, keycode: int) -> None:
        """Send an ``input keyevent``."""
        self._dev().keyevent(keycode)

    def wake(self) -> None:
        """Wake the screen (does not unlock; see docs/live-setup.md)."""
        self.key_event(KEYCODE_WAKEUP)

    def launch_app(self, package: str | None = None) -> None:
        """Bring the app (default: monobank, ``com.ftband.mono``) to the foreground."""
        pkg = package or self.config.app_package
        self._dev().app_start(pkg)
        log.info("adb.app_start", package=pkg)

    # -- teardown ------------------------------------------------------------

    def close(self) -> None:
        """Release the persistent swipe shell (idempotent; no zombie ``adb``).

        Safe to call even if a shell was never opened. An ``atexit`` hook in
        :class:`~bot2048.device.swipe_shell.PersistentSwipeShell` is the safety
        net if a caller forgets, but the live runner should call this on exit.
        """
        shell = self._swipe_shell
        self._swipe_shell = None
        if shell is not None:
            shell.close()
